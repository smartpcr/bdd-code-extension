// usage: BddGen <suite.yml> <out.g.cs>
// Accepts a trivial YAML subset:  "suite: Name" and "  - case title" lines under "cases:".
var (input, output) = (args[0], args[1]);
string suite = "Suite";
var cases = new List<string>();
foreach (var raw in File.ReadAllLines(input))
{
    var line = raw.Trim();
    if (line.StartsWith("suite:")) suite = line[6..].Trim();
    else if (line.StartsWith("- ")) cases.Add(line[2..].Trim());
}
static string Lit(string s) => "\"" + s.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";
var sb = new System.Text.StringBuilder();
sb.AppendLine("// <auto-generated/> from " + Path.GetFileName(input) + " at " + DateTime.Now.ToString("O"));
sb.AppendLine("using Microsoft.VisualStudio.TestTools.UnitTesting;");
sb.AppendLine("namespace BddGenerated;");
sb.AppendLine("[TestClass]");
sb.AppendLine($"public partial class {suite}");
sb.AppendLine("{");
for (int i = 0; i < cases.Count; i++)
{
    sb.AppendLine($"    [TestMethod(DisplayName = {Lit(cases[i])})]");
    sb.AppendLine($"    public void Case{i + 1}() {{ }}");
}
sb.AppendLine("}");
Directory.CreateDirectory(Path.GetDirectoryName(Path.GetFullPath(output))!);
File.WriteAllText(output, sb.ToString());
Console.WriteLine($"BddGen: wrote {output} ({cases.Count} cases)");
