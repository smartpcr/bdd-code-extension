<#
.SYNOPSIS
    suiterun generate for PowerShell (spec/test-plan.md). Dot-sourced by
    BddSuite.psm1.

.DESCRIPTION
    Reads a test project's bddsuite.tests.yaml, builds the test plan every
    runtime builds alike (conformance/generate/), and writes one
    <Id>.Bdd.Tests.ps1 per suite for Pester 5: a Describe named after the
    suite whose BeforeAll opens a session (Session.ps1) and runs the setup,
    whose AfterAll runs the teardown (a failure fails the container, not a
    test), and one It per case and examples row, tagged with the case's tags,
    with < and > escaped in its name (Pester reads them as a template).

        Invoke-BddSuiteGenerate -Config <file> [-Plan] [-Check] [-Provider pester] [-Out <dir>]
        suiterun.ps1 generate --config <file> [--plan] [--check] [--provider pester] [--out <dir>]
#>

$script:Providers = @('mstest', 'nunit', 'xunit', 'go', 'rust', 'node', 'vitest', 'jest', 'mocha', 'pester')
$script:ConfigKeys = @('suites', 'exclude', 'schemaRoot', 'provider', 'extensions', 'offlineActions', 'contextKeys', 'output')
$script:OutputKeys = @('folder', 'namespace', 'package')
$script:ReservedInSuite = @('Setup', 'Teardown', 'BeforeEach', 'AfterEach', 'TestContext', 'Session')
$script:GeneratedPrefix = '# Code generated by suiterun generate'
$script:GeneratedSuffix = '.Bdd.Tests.ps1'

function Read-BddSuiteTestsConfig {
    <#
    .SYNOPSIS
        One bddsuite.tests.yaml, its paths absolute against its own folder, or
        a throw saying what the schema refuses.
    #>
    [CmdletBinding()]
    param([Parameter(Mandatory)][string]$Path)
    $full = [IO.Path]::GetFullPath($(if ([IO.Path]::IsPathRooted($Path)) { $Path } else { Join-Path (Get-Location).Path $Path }))
    if (-not (Test-Path -LiteralPath $full -PathType Leaf)) { throw "$Path cannot be read: it does not exist." }
    try { $held = ConvertFrom-Yaml (Get-Content -LiteralPath $full -Raw) -Ordered } catch { throw "$Path is not valid YAML: $($_.Exception.Message)" }
    if ($held -isnot [System.Collections.IDictionary]) { throw "${Path}: it does not hold a YAML mapping." }
    foreach ($key in @($held.Keys)) {
        if ($script:ConfigKeys -cnotcontains $key) { throw "${Path}: $key is not a config key (spec/tests.config.schema.json)." }
    }
    $texts = {
        param([string]$Key, [bool]$Required)
        if (-not $held.Contains($Key)) {
            if ($Required) { throw "${Path}: $Key is required." }
            return , @()
        }
        $items = @($held[$Key])
        foreach ($item in $items) { if ($item -isnot [string] -or -not $item) { throw "${Path}: $Key is a list of non-empty strings." } }
        return , [string[]]$items
    }
    $suites = & $texts 'suites' $true
    if (-not $suites.Count) { throw "${Path}: suites names no glob." }
    $exclude = & $texts 'exclude' $false
    foreach ($one in @($suites) + @($exclude) + @([string]$held.schemaRoot)) {
        if ($one -and $one.Contains('\')) { throw "${Path}: $one uses a backslash; paths use forward slashes." }
    }
    if (-not $held.schemaRoot) { throw "${Path}: schemaRoot is required." }
    $folder = Split-Path $full -Parent
    $config = @{
        File = $full; Folder = $folder; Suites = $suites; Exclude = $exclude
        SchemaRoot = [IO.Path]::GetFullPath((Join-Path $folder ([string]$held.schemaRoot)))
        Provider = ''; Extensions = (& $texts 'extensions' $false); OfflineActions = $null
        ContextKeys = (& $texts 'contextKeys' $false); Output = @{}
    }
    if ($held.Contains('provider')) {
        if ($script:Providers -cnotcontains [string]$held.provider) { throw "${Path}: provider is one of $($script:Providers -join ', '), not $($held.provider)." }
        $config.Provider = [string]$held.provider
    }
    if ($held.Contains('offlineActions')) {
        $config.OfflineActions = & $texts 'offlineActions' $false
        foreach ($pattern in $config.OfflineActions) {
            $star = $pattern.IndexOf('*')
            if ($star -ge 0 -and (-not $pattern.EndsWith('.*') -or $star -ne $pattern.Length - 1)) { throw "${Path}: offlineActions: $pattern is a name or prefix.*, with no other star." }
        }
    }
    if ($held.Contains('output')) {
        if ($held.output -isnot [System.Collections.IDictionary]) { throw "${Path}: output is a mapping." }
        foreach ($key in @($held.output.Keys)) {
            if ($script:OutputKeys -cnotcontains $key) { throw "${Path}: output.$key is not an output key." }
            if ($held.output[$key]) { $config.Output[$key] = [string]$held.output[$key] }
        }
    }
    return $config
}

function ConvertTo-BddSuiteGlobRegex {
    # The folder a pattern starts in (its segments before the first wildcard), and a regex for the rest.
    param([string]$Root, [string]$Pattern)
    $segments = $Pattern -split '/'
    $fixed = 0
    while ($fixed -lt $segments.Count - 1 -and $segments[$fixed] -notmatch '[*?]') { $fixed++ }
    $start = $Root
    foreach ($segment in @($segments | Select-Object -First $fixed)) { $start = Join-Path $start $segment }
    $start = [IO.Path]::GetFullPath($start)
    $rest = ($segments | Select-Object -Skip $fixed) -join '/'
    $built = '^' + [regex]::Escape(($start -replace '\\', '/').TrimEnd('/')) + '/'
    for ($i = 0; $i -lt $rest.Length; $i++) {
        $one = $rest[$i]
        if ($one -eq '*' -and $i + 1 -lt $rest.Length -and $rest[$i + 1] -eq '*') {
            if ($i + 2 -lt $rest.Length -and $rest[$i + 2] -eq '/') { $built += '(?:.*/)?'; $i += 2 } else { $built += '.*'; $i += 1 }
        } elseif ($one -eq '*') { $built += '[^/]*' }
        elseif ($one -eq '?') { $built += '[^/]' }
        else { $built += [regex]::Escape([string]$one) }
    }
    $options = if ($IsWindows) { [Text.RegularExpressions.RegexOptions]::IgnoreCase } else { [Text.RegularExpressions.RegexOptions]::None }
    return @{ Start = $start; Regex = [regex]::new($built + '$', $options) }
}

function Select-BddSuiteFile {
    <#
    .SYNOPSIS
        The files the includes match and the excludes do not (spec/test-plan.md,
        Building the plan, step 1): ** any number of folders, * any text inside
        one name, ? one character, .. before the first wildcard. Relative to
        the folder, with forward slashes, in ordinal order.
    #>
    [CmdletBinding()]
    param([Parameter(Mandatory)][string]$Folder, [string[]]$Include = @(), [string[]]$Exclude = @())
    $root = [IO.Path]::GetFullPath($Folder)
    $rejected = @(foreach ($pattern in $Exclude) { (ConvertTo-BddSuiteGlobRegex -Root $root -Pattern $pattern).Regex })
    $found = [Collections.Generic.HashSet[string]]::new([StringComparer]::Ordinal)
    foreach ($pattern in $Include) {
        $glob = ConvertTo-BddSuiteGlobRegex -Root $root -Pattern $pattern
        if (-not (Test-Path -LiteralPath $glob.Start -PathType Container)) { continue }
        foreach ($file in [IO.Directory]::GetFiles($glob.Start, '*', [IO.SearchOption]::AllDirectories)) {
            $full = $file -replace '\\', '/'
            if (-not $glob.Regex.IsMatch($full)) { continue }
            if (@($rejected | Where-Object { $_.IsMatch($full) }).Count) { continue }
            $null = $found.Add(([IO.Path]::GetRelativePath($root, $file) -replace '\\', '/'))
        }
    }
    $sorted = [string[]]@($found)
    [Array]::Sort($sorted, [StringComparer]::Ordinal)
    return $sorted
}

function Get-BddSuiteIdentifier {
    <#
    .SYNOPSIS
        The identifier a name gives before collisions (spec/test-plan.md): its
        ASCII letters and digits, each word capitalised, the fallback for a
        name with none, N before a leading digit.
    #>
    [CmdletBinding()]
    param([AllowEmptyString()][string]$Name, [string]$Fallback)
    $built = [Text.StringBuilder]::new()
    $startOfWord = $true
    foreach ($one in $Name.ToCharArray()) {
        if ($one -notmatch '^[A-Za-z0-9]$') { $startOfWord = $true; continue }
        $null = $built.Append($(if ($startOfWord) { [char]::ToUpperInvariant($one) } else { $one }))
        $startOfWord = $false
    }
    $text = if ($built.Length) { $built.ToString() } else { $Fallback }
    if ($text -match '^[0-9]') { $text = "N$text" }
    return $text
}

function New-BddSuiteIdentifierSet {
    # Identifiers taken so far, compared ignoring ASCII case.
    param([string[]]$Reserved = @())
    $taken = [Collections.Generic.HashSet[string]]::new([StringComparer]::OrdinalIgnoreCase)
    foreach ($one in $Reserved) { $null = $taken.Add($one) }
    return , $taken
}

function Get-BddSuiteFreeIdentifier {
    # The next free identifier for a name: _2, _3, ... on a collision.
    param($Taken, [AllowEmptyString()][string]$Name, [string]$Fallback)
    $wanted = Get-BddSuiteIdentifier -Name $Name -Fallback $Fallback
    $candidate = $wanted
    for ($n = 2; $Taken.Contains($candidate); $n++) { $candidate = "${wanted}_$n" }
    $null = $Taken.Add($candidate)
    return $candidate
}

function Test-BddSuiteOfflineAction {
    # Whether an offlineActions pattern covers an action: the name itself, or prefix.* and a name under the prefix.
    param([string]$Pattern, [string]$Action)
    if ($Pattern.EndsWith('*')) { return $Action.StartsWith($Pattern.Substring(0, $Pattern.Length - 1), [StringComparison]::Ordinal) }
    return ($Pattern -ceq $Action)
}

function Get-BddSuiteActionUse {
    <#
    .SYNOPSIS
        Every action a suite can run: its hooks and every case's phases, meta
        steps expanded (imported ones too), and the step each wait polls.
    #>
    param([string]$File, $Model)
    $library = Import-SuiteLibrary -FilePath $File -Model $Model
    $definitions = Get-MetaStepDefinition -Model $Model -Imported $library.metaSteps
    $lists = [Collections.Generic.List[object]]::new()
    foreach ($hook in @('setup', 'beforeEach', 'afterEach', 'teardown')) {
        if ($Model.$hook) { $lists.Add(@(Expand-SuiteStepList -Steps $Model.$hook -Definitions $definitions -Where $hook)) }
    }
    foreach ($case in @(Expand-SuiteOutline -Cases $Model.tests)) {
        if ($case -isnot [System.Collections.IDictionary]) { continue }
        foreach ($phase in @('setup', 'steps', 'cleanup')) {
            if ($case.$phase) { $lists.Add(@(Expand-SuiteStepList -Steps $case.$phase -Definitions $definitions -Where "case $phase")) }
        }
    }
    $names = [Collections.Generic.List[string]]::new()
    foreach ($list in $lists) {
        foreach ($step in @($list)) {
            for ($current = $step; $current -is [System.Collections.IDictionary]; $current = $current.forStep) {
                if ($current.action) { $names.Add([string]$current.action) }
            }
        }
    }
    return , $names.ToArray()
}

function Get-BddSuiteDistinct {
    param([string[]]$Value)
    $seen = [Collections.Generic.HashSet[string]]::new([StringComparer]::Ordinal)
    return , [string[]]@(foreach ($one in $Value) { if ($null -ne $one -and $seen.Add($one)) { $one } })
}

function Get-BddSuitePlan {
    <#
    .SYNOPSIS
        A config's test plan, or the findings of every suite that does not lint
        clean (nothing is generated from a partial plan): @{ Plan; Findings }.
    #>
    [CmdletBinding()]
    param([Parameter(Mandatory)][hashtable]$Config)
    # The suites lint before any extension is loaded, so the context keys the
    # extensions add come from the config.
    $standIn = @{
        Name = "the config's context keys"; Path = ''; ModuleName = ''; ActionFiles = @(); Modules = @()
        ContextKeys = @($Config.ContextKeys); Options = @(); Lint = $null; CaseLimit = $null; EnvPrefix = $null; Start = $null; Cases = @{}
    }
    $composite = New-SuiteComposite -Extension @($standIn)
    $loaded = [Collections.Generic.List[hashtable]]::new()
    $findings = [Collections.Generic.List[object]]::new()
    foreach ($relative in (Select-BddSuiteFile -Folder $Config.Folder -Include $Config.Suites -Exclude $Config.Exclude)) {
        $full = [IO.Path]::GetFullPath((Join-Path $Config.Folder $relative))
        $model = ConvertFrom-Yaml (Get-Content -LiteralPath $full -Raw) -Ordered
        # A library declares and never runs: only a file with a suite key is a suite.
        if ($model -isnot [System.Collections.IDictionary] -or -not $model.Contains('suite')) { continue }
        foreach ($finding in Invoke-SuiteLintFile -FilePath $full -SchemaRoot $Config.SchemaRoot -RepositoryRoot $Config.Folder -Composite $composite) { $findings.Add($finding) }
        $loaded.Add(@{ Relative = $relative; Full = $full; Model = $model })
    }
    $sorted = @(Get-SortedSuiteDiagnostic -Diagnostic $findings.ToArray() | Where-Object { $null -ne $_ })
    if (Test-SuiteDiagnosticFailure -Diagnostic $sorted) { return @{ Plan = $null; Findings = $sorted } }

    $suiteIds = New-BddSuiteIdentifierSet
    $suites = foreach ($one in $loaded) {
        $model = $one.Model
        $name = [string]$model.suite
        $caseIds = New-BddSuiteIdentifierSet -Reserved $script:ReservedInSuite
        $suiteTags = @(@($model.tags) | Where-Object { $_ -is [string] })
        $cases = foreach ($entry in @($model.tests)) {
            if ($entry -isnot [System.Collections.IDictionary]) { continue }
            $outline = if (@($entry.examples).Count -and $null -ne $entry.examples) { [string]$entry.name } else { $null }
            foreach ($expanded in @(Expand-SuiteOutline -Cases @($entry))) {
                $caseName = [string]$expanded.name
                $planned = [ordered]@{
                    name = $caseName
                    id   = Get-BddSuiteFreeIdentifier -Taken $caseIds -Name $caseName -Fallback 'Case'
                    tags = Get-BddSuiteDistinct -Value @(@($expanded.tags | Where-Object { $_ } | ForEach-Object { [string]$_ }) + $suiteTags)
                }
                if ($null -ne $outline) { $planned['outline'] = $outline; $planned['row'] = $expanded.__row }
                $planned
            }
        }
        $guardedBy = @()
        if ($null -ne $Config.OfflineActions) {
            $used = Get-BddSuiteDistinct -Value (Get-BddSuiteActionUse -File $one.Full -Model $model)
            $guardedBy = @($used | Where-Object {
                    $action = $_
                    -not @($Config.OfflineActions | Where-Object { Test-BddSuiteOfflineAction -Pattern $_ -Action $action }).Count
                })
            $sortedGuard = [string[]]$guardedBy
            [Array]::Sort($sortedGuard, [StringComparer]::Ordinal)
            $guardedBy = @($sortedGuard)
        }
        [ordered]@{
            file = $one.Relative; fullPath = $one.Full; name = $name
            id = Get-BddSuiteFreeIdentifier -Taken $suiteIds -Name $name -Fallback 'Suite'
            tags = Get-BddSuiteDistinct -Value $suiteTags; guarded = [bool]$guardedBy.Count; guardedBy = $guardedBy; cases = @($cases)
        }
    }
    return @{ Plan = @{ Config = $Config; Suites = @($suites) }; Findings = $sorted }
}

function ConvertTo-BddSuitePlanJson {
    <#
    .SYNOPSIS
        The plan as spec/test-plan.schema.json describes it, indented, with
        non-ASCII characters as themselves.
    #>
    [CmdletBinding()]
    param([Parameter(Mandatory)][hashtable]$Plan)
    $suites = @(foreach ($s in $Plan.Suites) {
            [ordered]@{
                file = $s.file; name = $s.name; id = $s.id; tags = @($s.tags); guarded = $s.guarded; guardedBy = @($s.guardedBy)
                cases = @(foreach ($c in $s.cases) {
                        $case = [ordered]@{ name = $c.name; id = $c.id }
                        if ($c.Contains('outline')) { $case['outline'] = $c.outline; $case['row'] = $c.row }
                        $case['tags'] = @($c.tags)
                        $case
                    })
            }
        })
    $json = ConvertTo-Json -InputObject ([ordered]@{ planVersion = 1; suites = $suites }) -Depth 12 -EscapeHandling Default
    return $json -replace "`r", ''
}

function ConvertTo-BddSuitePesterText {
    # A PowerShell single-quoted string; with -Name, < and > escaped, which Pester reads as a template in a test's name.
    param([AllowEmptyString()][string]$Text, [switch]$Name)
    $quoted = $Text.Replace("'", "''")
    if ($Name) { $quoted = $quoted.Replace('<', '`<').Replace('>', '`>') }
    return "'$quoted'"
}

function Get-BddSuiteRelativePath {
    # A path relative to a folder, with forward slashes.
    param([string]$Folder, [string]$Path)
    return ([IO.Path]::GetRelativePath($Folder, $Path) -replace '\\', '/')
}

function ConvertTo-BddSuitePesterFile {
    <#
    .SYNOPSIS
        One file per planned suite, for Pester 5, in the output folder: @{ Name; Text }.
    #>
    [CmdletBinding()]
    param([Parameter(Mandatory)][object[]]$Plans, [Parameter(Mandatory)][string]$Folder)
    foreach ($plan in $Plans) {
        $extensions = @(foreach ($one in $plan.Config.Extensions) {
                $full = [IO.Path]::GetFullPath((Join-Path $plan.Config.Folder $one))
                "(Join-Path `$PSScriptRoot $(ConvertTo-BddSuitePesterText (Get-BddSuiteRelativePath $Folder $full)))"
            })
        $schemaRoot = Get-BddSuiteRelativePath $Folder $plan.Config.SchemaRoot
        foreach ($suite in $plan.Suites) {
            $file = Get-BddSuiteRelativePath $Folder $suite.fullPath
            $lines = [Collections.Generic.List[string]]::new()
            $lines.Add("$($script:GeneratedPrefix) (pester) from $file. DO NOT EDIT.")
            $lines.Add("# Needs the BddSuite module imported (or on PSModulePath) and Pester 5; see the BddSuite README.")
            $lines.Add("Describe $(ConvertTo-BddSuitePesterText $suite.name -Name) {")
            $lines.Add('    BeforeAll {')
            # Import-Module by name searches PSModulePath only, so a runtime the driver loaded by path is used as it is.
            $lines.Add('        if (-not (Get-Module BddSuite)) { Import-Module BddSuite -DisableNameChecking }')
            $lines.Add("        `$context = Get-BddSuiteTestContext -SchemaRoot (Join-Path `$PSScriptRoot $(ConvertTo-BddSuitePesterText $schemaRoot)) -Extension @($($extensions -join ', '))")
            $lines.Add("        `$session = Open-BddSuiteSession -Path (Join-Path `$PSScriptRoot $(ConvertTo-BddSuitePesterText $file)) -Shown $(ConvertTo-BddSuitePesterText $suite.file) -Context `$context$(if ($suite.guarded) { ' -Guarded' })")
            $lines.Add('        Invoke-BddSuiteSetup -Session $session')
            $lines.Add('    }')
            $lines.Add('    AfterAll {')
            $lines.Add('        Complete-BddSuiteSession -Session $session')
            $lines.Add('    }')
            foreach ($case in $suite.cases) {
                $tags = if (@($case.tags).Count) { ' -Tag ' + (@($case.tags | ForEach-Object { ConvertTo-BddSuitePesterText $_ }) -join ', ') } else { '' }
                $lines.Add('')
                $lines.Add("    It $(ConvertTo-BddSuitePesterText $case.name -Name)$tags {")
                $lines.Add("        `$outcome = Invoke-BddSuiteTest -Session `$session -Case $(ConvertTo-BddSuitePesterText $case.name)")
                $lines.Add('        if ($outcome.Skipped) { Set-ItResult -Skipped -Because $outcome.Message }')
                $lines.Add('    }')
            }
            $lines.Add('}')
            @{ Name = "$($suite.id)$($script:GeneratedSuffix)"; Text = (($lines -join "`n") + "`n") }
        }
    }
}

function Write-BddSuiteGeneratedFile {
    <#
    .SYNOPSIS
        Write the files into the folder, rewriting only those that changed,
        and remove every other file there this generator wrote (its first line
        says so), never anyone else's. With -Check, write nothing and name
        what is stale.
    #>
    [CmdletBinding()]
    param([Parameter(Mandatory)][string]$Folder, [object[]]$File = @(), [switch]$Check)
    $outcome = @{ Written = [Collections.Generic.List[string]]::new(); Removed = [Collections.Generic.List[string]]::new(); Stale = [Collections.Generic.List[string]]::new() }
    if (-not $Check -and -not (Test-Path -LiteralPath $Folder)) { New-Item -ItemType Directory -Path $Folder -Force | Out-Null }
    $wanted = @{}
    foreach ($one in $File) { $wanted[$one.Name] = $one.Text }
    $utf8 = [Text.UTF8Encoding]::new($false)
    foreach ($name in @($wanted.Keys | Sort-Object)) {
        $target = Join-Path $Folder $name
        if ((Test-Path -LiteralPath $target) -and ([IO.File]::ReadAllText($target) -ceq $wanted[$name])) { continue }
        if ($Check) { $outcome.Stale.Add($name) } else { [IO.File]::WriteAllText($target, $wanted[$name], $utf8); $outcome.Written.Add($name) }
    }
    if (Test-Path -LiteralPath $Folder) {
        foreach ($item in @(Get-ChildItem -LiteralPath $Folder -File -Filter "*$($script:GeneratedSuffix)" | Sort-Object Name)) {
            if ($wanted.ContainsKey($item.Name)) { continue }
            if (-not ([IO.File]::ReadAllText($item.FullName)).StartsWith($script:GeneratedPrefix, [StringComparison]::Ordinal)) { continue }
            if ($Check) { $outcome.Stale.Add($item.Name) } else { Remove-Item -LiteralPath $item.FullName; $outcome.Removed.Add($item.Name) }
        }
    }
    return $outcome
}

function Invoke-BddSuiteGenerate {
    <#
    .SYNOPSIS
        generate: build each config's test plan and write the Pester tests.
    .DESCRIPTION
        With -Plan it returns the one config's plan; with -Check it writes
        nothing and exits 1 naming each stale file. A suite that does not lint
        clean refuses the whole run (exit 2), writing nothing. Returns
        @{ Code; Out; Errors }, as the command line prints them.
    #>
    [CmdletBinding()]
    param([Parameter(Mandatory)][string[]]$Config, [switch]$Plan, [switch]$Check, [string]$Provider = '', [string]$Out = '')
    $refused = { param([string]$Why) @{ Code = 2; Out = ''; Errors = $Why } }
    $plans = [Collections.Generic.List[hashtable]]::new()
    $findings = [Collections.Generic.List[string]]::new()
    try {
        foreach ($one in $Config) {
            $built = Get-BddSuitePlan -Config (Read-BddSuiteTestsConfig -Path $one)
            if ($built.Plan) { $plans.Add($built.Plan) } else { foreach ($f in $built.Findings) { $findings.Add(((Format-SuiteDiagnostic $f) -replace "`r", '')) } }
        }
    } catch { return (& $refused $_.Exception.Message) }
    if ($findings.Count) { return (& $refused (($findings + 'Nothing was generated: every suite has to lint clean first.') -join "`n")) }
    if ($Plan) {
        if ($plans.Count -ne 1) { return (& $refused "--plan prints one config's plan; give one --config.") }
        return @{ Code = 0; Out = (ConvertTo-BddSuitePlanJson -Plan $plans[0]); Errors = '' }
    }
    $first = $plans[0].Config
    $chosen = if ($Provider) { $Provider } elseif ($first.Provider) { $first.Provider } else { 'pester' }
    if ($chosen -cne 'pester') { return (& $refused "$chosen is not a PowerShell provider; the PowerShell runtime generates for pester.") }
    $folder = if ($Out) { [IO.Path]::GetFullPath($(if ([IO.Path]::IsPathRooted($Out)) { $Out } else { Join-Path (Get-Location).Path $Out })) }
    elseif ($first.Output.folder) { [IO.Path]::GetFullPath((Join-Path $first.Folder $first.Output.folder)) } else { $first.Folder }
    $files = @(ConvertTo-BddSuitePesterFile -Plans $plans.ToArray() -Folder $folder)
    $outcome = Write-BddSuiteGeneratedFile -Folder $folder -File $files -Check:$Check
    if ($Check) {
        if (-not $outcome.Stale.Count) { return @{ Code = 0; Out = "$($files.Count) generated file(s) are up to date."; Errors = '' } }
        return @{ Code = 1; Out = ((@($outcome.Stale | ForEach-Object { "stale: $_" }) + 'Run suiterun generate to write them again.') -join "`n"); Errors = '' }
    }
    $tests = 0
    foreach ($p in $plans) { foreach ($s in $p.Suites) { $tests += @($s.cases).Count } }
    $suites = 0
    foreach ($p in $plans) { $suites += @($p.Suites).Count }
    $lines = @($outcome.Written | ForEach-Object { "wrote $_" }) + @($outcome.Removed | ForEach-Object { "removed $_" }) + "pester: $suites suite(s), $tests test(s) in $folder"
    return @{ Code = 0; Out = ($lines -join "`n"); Errors = '' }
}
