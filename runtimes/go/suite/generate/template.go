package generate

import (
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

// generatedPrefix starts every file the generator writes: Go's own marker for
// generated code, and how the generator recognises a file it may replace or
// delete.
const generatedPrefix = "// Code generated by suiterun generate"

// MainFile is the file holding the package's TestMain.
const MainFile = "bddsuite_main_bdd_test.go"

// File is one file the generator writes: its name in the output folder and its
// text.
type File struct {
	Name string
	Text string
}

// Outcome is what writing (or checking) the output folder found.
type Outcome struct {
	Written, Removed, Stale []string
}

func header(source string) string {
	return fmt.Sprintf("%s (go) from %s. DO NOT EDIT.\n\n", generatedPrefix, source)
}

// relative is a path as generated code holds it: relative to the package
// folder (go test runs there), forward slashes, so committed files are the
// same on every machine.
func relative(folder, path string) (string, error) {
	out, err := filepath.Rel(folder, path)
	if err != nil {
		return "", err
	}
	return filepath.ToSlash(out), nil
}

// extensionImport splits "import/path.Symbol" into the import path and the
// exported variable holding the extension.
func extensionImport(reference string) (string, string, error) {
	slash := strings.LastIndex(reference, "/")
	dot := strings.LastIndex(reference, ".")
	if dot <= slash || dot == len(reference)-1 {
		return "", "", fmt.Errorf("extensions: %s is not import/path.Name, the exported extension.Extension to register", reference)
	}
	return reference[:dot], reference[dot+1:], nil
}

// Render is the Go code for the plans: one file per suite and the package's
// TestMain. Every plan goes in one package (one TestMain per package).
func Render(plans []*Plan, folder, packageName string) ([]File, error) {
	var files []File
	names := map[string]bool{}
	sources := []string{}
	type imported struct{ path, symbol string }
	var extensions []imported
	seen := map[string]bool{}
	for _, plan := range plans {
		sources = append(sources, filepath.Base(plan.Config.File))
		for _, reference := range plan.Config.Extensions {
			if seen[reference] {
				continue
			}
			seen[reference] = true
			path, symbol, err := extensionImport(reference)
			if err != nil {
				return nil, err
			}
			extensions = append(extensions, imported{path, symbol})
		}
		for _, one := range plan.Suites {
			name := one.ID + "_bdd_test.go"
			if names[strings.ToLower(name)] {
				return nil, fmt.Errorf("two configs generate %s; give each its own output.folder", name)
			}
			names[strings.ToLower(name)] = true
			suitePath, err := relative(folder, one.FullPath)
			if err != nil {
				return nil, err
			}
			schemaPath, err := relative(folder, plan.Config.SchemaRoot)
			if err != nil {
				return nil, err
			}
			code := strings.Builder{}
			code.WriteString(header(one.File))
			fmt.Fprintf(&code, "package %s\n\nimport (\n\t\"testing\"\n\n\t\"github.com/smartpcr/bdd-code-extension/runtimes/go/suite/suitetest\"\n)\n\n", packageName)
			fmt.Fprintf(&code, "// TestSuite_%s runs the suite %s (%s): its setup before the first case\n// that runs, each case as a subtest, its teardown when they are done.\n", one.ID, one.Name, one.File)
			fmt.Fprintf(&code, "func TestSuite_%s(t *testing.T) {\n\tsuite := suitetest.Open(t, %s, %s, %t)\n", one.ID, strconv.Quote(suitePath), strconv.Quote(schemaPath), one.Guarded)
			for _, held := range one.Cases {
				fmt.Fprintf(&code, "\tt.Run(%s, suite.Case(%s))\n", strconv.Quote(held.Name), strconv.Quote(held.Name))
			}
			code.WriteString("}\n")
			formatted, err := format.Source([]byte(code.String()))
			if err != nil {
				return nil, fmt.Errorf("%s: %w", name, err)
			}
			files = append(files, File{Name: name, Text: string(formatted)})
		}
	}
	main := strings.Builder{}
	main.WriteString(header(strings.Join(sources, ", ")))
	fmt.Fprintf(&main, "package %s\n\nimport (\n\t\"os\"\n\t\"testing\"\n\n\t\"github.com/smartpcr/bdd-code-extension/runtimes/go/suite/suitetest\"\n", packageName)
	arguments := []string{"m"}
	for index, one := range extensions {
		alias := fmt.Sprintf("extension%d", index)
		fmt.Fprintf(&main, "\t%s %s\n", alias, strconv.Quote(one.path))
		arguments = append(arguments, alias+"."+one.symbol)
	}
	main.WriteString(")\n\n// TestMain starts the run context once, before any suite, and writes its\n// trace after the last (spec/session.md).\n")
	fmt.Fprintf(&main, "func TestMain(m *testing.M) {\n\tos.Exit(suitetest.Main(%s))\n}\n", strings.Join(arguments, ", "))
	formatted, err := format.Source([]byte(main.String()))
	if err != nil {
		return nil, fmt.Errorf("%s: %w", MainFile, err)
	}
	return append(files, File{Name: MainFile, Text: string(formatted)}), nil
}

func owned(path string) bool {
	text, err := os.ReadFile(path)
	return err == nil && strings.HasPrefix(string(text), generatedPrefix)
}

// Write brings the folder in line with the files: a file is written only when
// its text changed, and a generated file no suite needs any more is deleted.
// Only files carrying the generator's marker are replaced or deleted. With
// check, it only says which differ.
func Write(folder string, files []File, check bool) (Outcome, error) {
	outcome := Outcome{}
	if !check {
		if err := os.MkdirAll(folder, 0o755); err != nil {
			return outcome, err
		}
	}
	wanted := map[string]bool{}
	for _, file := range files {
		wanted[strings.ToLower(file.Name)] = true
		path := filepath.Join(folder, file.Name)
		current, err := os.ReadFile(path)
		if err == nil && string(current) == file.Text {
			continue
		}
		if check {
			outcome.Stale = append(outcome.Stale, file.Name)
			continue
		}
		if err := os.WriteFile(path, []byte(file.Text), 0o644); err != nil {
			return outcome, err
		}
		outcome.Written = append(outcome.Written, file.Name)
	}
	present, _ := filepath.Glob(filepath.Join(folder, "*_bdd_test.go"))
	sort.Strings(present)
	for _, path := range present {
		name := filepath.Base(path)
		if wanted[strings.ToLower(name)] || !owned(path) {
			continue
		}
		if check {
			outcome.Stale = append(outcome.Stale, name)
			continue
		}
		if err := os.Remove(path); err != nil {
			return outcome, err
		}
		outcome.Removed = append(outcome.Removed, name)
	}
	return outcome, nil
}
