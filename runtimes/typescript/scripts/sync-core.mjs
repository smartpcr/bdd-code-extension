// Writes src/coreCatalog.ts from the repository's spec/core.catalog.yaml: the
// core this runtime carries for `imports: [ bdd-suite:core ]` (spec/README.md;
// docs/packages, DEC-P07). A module rather than a file beside dist/, so the
// core travels with any bundle of this package. With --check it only compares
// and exits 1 on a difference; a unit test does the same comparison.
import { readFileSync, writeFileSync } from 'node:fs';

const spec = new URL('../../../spec/core.catalog.yaml', import.meta.url);
const target = new URL('../src/coreCatalog.ts', import.meta.url);
const text = readFileSync(spec, 'utf8').replace(/\r\n/g, '\n');
const wanted = `// Generated by scripts/sync-core.mjs from spec/core.catalog.yaml. Do not edit:
// run npm run sync-core after a change to the spec's core.
/** The core catalog this runtime carries, for the import bdd-suite:core. */
export const CORE_CATALOG = ${JSON.stringify(text)};
`;
if (process.argv.includes('--check')) {
  const same = readFileSync(target, 'utf8').replace(/\r\n/g, '\n') === wanted;
  console.log(same ? 'src/coreCatalog.ts is the spec\'s core' : 'src/coreCatalog.ts differs from spec/core.catalog.yaml; run npm run sync-core');
  process.exit(same ? 0 : 1);
}
writeFileSync(target, wanted);
console.log('src/coreCatalog.ts written');
