// The TypeScript a plan becomes: one <Id>.bdd.test.ts per suite, for
// node:test, Vitest, Jest or Mocha. Each file imports the framework's own functions
// and passes them to the testing module's adapter (src/testing), so one
// module serves the three frameworks. Paths are relative to the generated
// file, so the text does not depend on where the repository is checked out.
import * as fs from 'node:fs';
import * as path from 'node:path';
import { Plan } from './plan.js';

/** The providers this runtime generates for. */
export const TYPESCRIPT_PROVIDERS = ['node', 'vitest', 'jest', 'mocha'] as const;
export type TypeScriptProvider = (typeof TYPESCRIPT_PROVIDERS)[number];

/** The start of the first line of every file the generator writes, and of no other. */
export const GENERATED_PREFIX = '// Code generated by suiterun generate';
export const SUFFIX = '.bdd.test.ts';

export interface GeneratedFile {
  name: string;
  text: string;
}

const slashes = (p: string) => p.replace(/\\/g, '/');
const relativeTo = (folder: string, target: string) => {
  const rel = slashes(path.relative(folder, target));
  return rel.startsWith('.') ? rel : `./${rel}`;
};

/** The framework's functions, as each template imports and adapts them. */
const FRAMEWORK: Record<TypeScriptProvider, { imports: string; adapter: string }> = {
  node: {
    imports: "import { after, before, describe, it } from 'node:test';",
    // Every node:test function is called from this file, not from the
    // runtime: node names the file a test was declared from in its events,
    // and the runtime's reporter tells files apart by it when their events
    // interleave (testing/node-reporter.ts).
    adapter: '{ describe: (name, body) => describe(name, body), it: (name, body) => it(name, body), before: body => before(body), after: body => after(body), '
      + 'skip: (name, reason) => it(name, { skip: reason }, () => {}) }',
  },
  vitest: {
    imports: "import { afterAll, beforeAll, describe, it } from 'vitest';",
    adapter: '{ describe, it, before: beforeAll, after: afterAll, skip: name => it.skip(name, () => {}) }',
  },
  jest: {
    imports: "import { afterAll, beforeAll, describe, it } from '@jest/globals';",
    adapter: '{ describe, it, before: beforeAll, after: afterAll, skip: name => it.skip(name, () => {}) }',
  },
  mocha: {
    imports: "import { after, before, describe, it } from 'mocha';",
    adapter: '{ describe, it, before, after, skip: name => it.skip(name, () => {}) }',
  },
};

/** An extension reference module#name, with a relative module resolved from the config's folder to the output folder. */
export function extensionImport(reference: string, configFolder: string, outputFolder: string): { module: string; name: string } {
  const at = reference.lastIndexOf('#');
  const module = reference.slice(0, at);
  const name = reference.slice(at + 1);
  if (at <= 0 || !/^[A-Za-z_$][\w$]*$/.test(name)) throw new Error(`${reference} is not an extension reference: write module#name, as in my-actions#shop.`);
  return { module: module.startsWith('.') ? relativeTo(outputFolder, path.resolve(configFolder, module)) : module, name };
}

/** One file per planned suite, for the provider, in the output folder. */
export function render(plans: Plan[], folder: string, provider: TypeScriptProvider): GeneratedFile[] {
  const files: GeneratedFile[] = [];
  for (const plan of plans) {
    const extensions = plan.config.extensions.map(r => extensionImport(r, plan.config.folder, folder));
    for (const suite of plan.suites) {
      const lines = [
        `${GENERATED_PREFIX} (${provider}) from ${relativeTo(folder, suite.fullPath)}. DO NOT EDIT.`,
        FRAMEWORK[provider].imports,
        "import { suite } from '@bdd-suite/runtime/testing';",
        ...extensions.map((e, i) => `import { ${e.name} as extension${i} } from ${JSON.stringify(e.module)};`),
        '',
        `suite(${FRAMEWORK[provider].adapter}, [${extensions.map((_, i) => `extension${i}`).join(', ')}], import.meta.url, {`,
        `  file: ${JSON.stringify(relativeTo(folder, suite.fullPath))},`,
        `  shown: ${JSON.stringify(suite.file)},`,
        `  schemaRoot: ${JSON.stringify(relativeTo(folder, plan.config.schemaRoot))},`,
        `  name: ${JSON.stringify(suite.name)},`,
        `  guarded: ${suite.guarded},`,
        '  cases: [',
        ...suite.cases.map(c => `    ${JSON.stringify(c.name)},`),
        '  ],',
        '});',
        '',
      ];
      files.push({ name: `${suite.id}${SUFFIX}`, text: lines.join('\n') });
    }
  }
  return files;
}

export interface WriteOutcome {
  written: string[];
  removed: string[];
  /** With check: every file that differs from what would be written, or that would be removed. */
  stale: string[];
}

/**
 * Writes the files into the folder, rewriting only those that changed, and
 * removes every other file there this generator wrote (its first line says
 * so), never anyone else's. With check it writes nothing and names what is
 * stale.
 */
export function write(folder: string, files: GeneratedFile[], check: boolean): WriteOutcome {
  const outcome: WriteOutcome = { written: [], removed: [], stale: [] };
  if (!check) fs.mkdirSync(folder, { recursive: true });
  const wanted = new Map(files.map(f => [f.name, f.text]));
  for (const [name, text] of wanted) {
    const target = path.join(folder, name);
    if (fs.existsSync(target) && fs.readFileSync(target, 'utf8') === text) continue;
    if (check) outcome.stale.push(name);
    else {
      fs.writeFileSync(target, text);
      outcome.written.push(name);
    }
  }
  const present = fs.existsSync(folder) ? fs.readdirSync(folder).filter(n => n.endsWith(SUFFIX) && !wanted.has(n)) : [];
  for (const name of present.sort()) {
    const target = path.join(folder, name);
    if (!fs.readFileSync(target, 'utf8').startsWith(GENERATED_PREFIX)) continue;
    if (check) outcome.stale.push(name);
    else {
      fs.rmSync(target);
      outcome.removed.push(name);
    }
  }
  outcome.stale.sort();
  return outcome;
}

/**
 * The provider when the config names none (DEC-T10): from the package.json
 * nearest the output folder, Vitest, Jest or Mocha when it depends on one,
 * else node:test.
 */
export function detectProvider(folder: string): TypeScriptProvider {
  const at = path.resolve(folder);
  const manifest = path.join(at, 'package.json');
  if (fs.existsSync(manifest)) {
    const json = JSON.parse(fs.readFileSync(manifest, 'utf8')) as Record<string, Record<string, string> | undefined>;
    const deps = { ...json.dependencies, ...json.devDependencies };
    return 'vitest' in deps ? 'vitest' : 'jest' in deps ? 'jest' : 'mocha' in deps ? 'mocha' : 'node';
  }
  return path.dirname(at) === at ? 'node' : detectProvider(path.dirname(at));
}
